"""Print a Markdown table of installed distributions and their declared licenses.

Reads package metadata only (License-Expression, License, classifiers). Declared
metadata can be incomplete or wrong; it is a starting point for review, not a
legal determination. Usage: python tools/list_licenses.py > docs/third-party-licenses.md
"""

import importlib.metadata as md
import sys

SKIP = {"cl-workbench"}


def declared(meta) -> str:
    expr = meta.get("License-Expression")
    if expr:
        return expr
    lic = (meta.get("License") or "").strip().splitlines()
    first = lic[0][:60] if lic else ""
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    parts = [p for p in (first, "; ".join(classifiers)) if p]
    return " / ".join(parts) or "not declared"


def main() -> None:
    rows = []
    for dist in md.distributions():
        name = dist.metadata["Name"]
        if not name or name.lower() in SKIP:
            continue
        rows.append((name.lower(), dist.version, declared(dist.metadata).replace("|", "/")))
    print("# Third-party packages in the pinned environment\n")
    print(f"Generated by `tools/list_licenses.py` from installed package metadata (Python {sys.version.split()[0]}). "
          "Declared metadata can be incomplete or wrong; review before redistributing anything.\n")
    print("| Package | Version | Declared license |\n| --- | --- | --- |")
    for name, ver, lic in sorted(rows):
        print(f"| {name} | {ver} | {lic} |")


if __name__ == "__main__":
    main()
